@njit
def _erfcx(x: float) -> float:
    """Scaled complementary error function for nonnegative arguments (Cody 1969)."""
    if x < 0.46875:
        return np.exp(x * x) * erfc(x)
    if x <= 4:
        numerator, denominator = _C[8] * x, x
        for i in range(7):
            numerator = (numerator + _C[i]) * x
            denominator = (denominator + _D[i]) * x
        return (numerator + _C[7]) / (denominator + _D[7])
    if x > 6.71e7:
        return 0.56418958354775628695 / x
    w = (1 / x) * (1 / x)
    numerator, denominator = _P[5] * w, w
    for i in range(4):
        numerator = (numerator + _P[i]) * w
        denominator = (denominator + _Q[i]) * w
    return (0.56418958354775628695 - w * (numerator + _P[4]) / (denominator + _Q[4])) / x


@njit
def _yprime_tail(w: float) -> float:
    """Rational correction to Y'(h) in the far left Gaussian tail."""
    return (
        w * (-2.9999999999994663866 + w * (-1.7556263323542206288e2 + w * (-3.4735035445495633334e3
        + w * (-2.7805745693864308643e4 + w * (-8.3836021460741980839e4 - 6.6818249032616849037e4 *
        w))))) / (1 + w * (6.3520877744831739102e1 + w * (1.4404389037604337538e3 + w *
        (1.4562545638507033944e4 + w * (6.6886794165651675684e4 + w * (1.2569970380923908488e5 +
        6.9286518679803751694e4 * w))))))
    )


@njit
def _yprime(h: float) -> float:
    """Evaluate 1 + h * Phi(h) / phi(h) for nonpositive h without tail cancellation."""
    if h < -4:
        w = 1 / (h * h)
        return w * (1 + _yprime_tail(w))
    if h <= -0.46875:
        return (
            (1.0000000000594317229 - h * (6.1911449879694112749e-1 - h * (2.2180844736576013957e-1 -
            h * (4.5650900351352987865e-2 - h * (5.545521007735379052e-3 - h *
            (3.0717392274913902347e-4 - h * (4.2766597835908713583e-8 + 8.4592436406580605619e-10 *
            h))))))) / (1 - h * (1.8724286369589162071 - h * (1.5685497236077651429 - h *
            (7.6576489836589035112e-1 - h * (2.3677701403094640361e-1 - h *
            (4.6762548903194957675e-2 - h * (5.5290453576936595892e-3 - 3.0822020417927147113e-4 *
            h)))))))
        )
    return 1 + h * SQRT_PI_OVER_TWO * _erfcx(-(1 / SQRT_TWO) * h)


@njit
def _one_minus_erfcx(x: float) -> float:
    """Evaluate 1 - erfcx(x), using a rational approximation near zero."""
    if x < -1.0 / 5.0 or x > 1.0 / 3.0:
        return 1 - _erfcx(x)
    return (
        x * (1.128379167095512573896 - x * (1.0000000000000002 + x * (1.1514967181784756 + x *
        (5.7689001208873741e-1 + x * (1.4069188744609651e-1 + 1.4069285713634565e-2 * x)))) / (1 + x
        * (1.9037494962421563 + x * (1.5089908593742723 + x * (6.2486081658640257e-1 + x *
        (1.358008134514386e-1 + 1.2463320728346347e-2 * x))))))
    )


